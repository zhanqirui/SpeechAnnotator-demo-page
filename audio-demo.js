const makeLiveMetaHtml = (meta) => Object.entries(meta)
  .map(([key, value]) => {
    const shownValue = key.endsWith("time") && typeof value === "number" ? `${(value / 1000).toFixed(2)}s` : value;
    return `<div><span>${escapeHtml(metaLabels[key] || key)}</span><p>${escapeHtml(shownValue || "None")}</p></div>`;
  })
  .join("");

const makeCurrentSegmentHtml = (segment) => `
  <article class="current-segment-panel">
    <div class="current-segment-head">
      <span>${escapeHtml(segment.speaker)}</span>
      <strong>${formatTime(segment.start)} - ${formatTime(segment.end)}</strong>
    </div>
    <div class="current-text-card">
      <span>Text</span>
      <p>${escapeHtml(segment.text)}</p>
    </div>
  </article>
`;

const createSampleCard = (sample, index) => {
  const section = document.createElement("article");
  section.className = "sample-player";
  const sampleLabel = sample.title || `Sample ${index + 1}`;
  const titleHtml = sample.title ? `<h3>${escapeHtml(sample.title)}</h3>` : "";
  const sampleDuration = Math.max(0.01, Number((sample.clipEnd - sample.clipStart).toFixed(2)));
  const sampleDurationLabel = formatTime(sampleDuration);
  section.innerHTML = `
    <div class="sample-player-head">
      <div>
        <span>Sample ${index + 1}</span>
        ${titleHtml}
      </div>
    </div>
    <audio preload="metadata" src="${escapeHtml(sample.audio)}"></audio>
    <div class="player-controls">
      <button type="button" class="play-button" aria-label="Play ${escapeHtml(sampleLabel)}">Play</button>
      <div class="time-readout"><span class="current-time">00:00</span><span> / ${sampleDurationLabel}</span></div>
    </div>
    <input class="segment-progress" type="range" min="0" max="${sampleDuration}" step="0.01" value="0" aria-label="${escapeHtml(sampleLabel)} progress" />
    <div class="current-segment-root"></div>
    <div class="metadata-screen" aria-live="polite">
      <div class="metadata-screen-head">
        <span>Current segment metadata</span>
        <strong>Ready</strong>
      </div>
      <div class="live-meta-grid"></div>
    </div>
  `;

  const audio = section.querySelector("audio");
  const button = section.querySelector(".play-button");
  const progress = section.querySelector(".segment-progress");
  const currentTime = section.querySelector(".current-time");
  const metadataStatus = section.querySelector(".metadata-screen-head strong");
  const liveMetaGrid = section.querySelector(".live-meta-grid");
  const currentSegmentRoot = section.querySelector(".current-segment-root");
  let activeSegmentId = "";

  const seekToClipStart = () => {
    if (!Number.isFinite(audio.currentTime) || audio.currentTime < sample.clipStart || audio.currentTime >= sample.clipEnd) {
      audio.currentTime = sample.clipStart;
    }
  };

  const setActiveSegment = () => {
    const absolute = audio.currentTime;
    const elapsed = Math.min(sampleDuration, Math.max(0, absolute - sample.clipStart));
    progress.value = elapsed.toString();
    currentTime.textContent = formatTime(elapsed);

    const active = sample.segments.find((segment) => absolute >= segment.start && absolute <= segment.end);

    if (active) {
      metadataStatus.textContent = `${active.speaker} / ${formatTime(active.start - sample.clipStart)} - ${formatTime(active.end - sample.clipStart)}`;
      if (activeSegmentId !== active.id) {
        activeSegmentId = active.id;
        liveMetaGrid.innerHTML = makeLiveMetaHtml(active.meta);
        currentSegmentRoot.innerHTML = makeCurrentSegmentHtml({
          ...active,
          start: active.start - sample.clipStart,
          end: active.end - sample.clipStart,
        });
      }
    }

    if (audio.currentTime >= sample.clipEnd) {
      audio.pause();
      audio.currentTime = sample.clipEnd;
      progress.value = sampleDuration.toString();
      currentTime.textContent = sampleDurationLabel;
      button.textContent = "Replay";
    }
  };

  button.addEventListener("click", async () => {
    if (audio.paused) {
      seekToClipStart();
      await audio.play();
      button.textContent = "Pause";
    } else {
      audio.pause();
      button.textContent = "Play";
    }
  });

  progress.addEventListener("input", () => {
    audio.currentTime = sample.clipStart + Number(progress.value);
    setActiveSegment();
  });

  audio.addEventListener("loadedmetadata", () => {
    seekToClipStart();
    setActiveSegment();
  });
  audio.addEventListener("timeupdate", setActiveSegment);
  audio.addEventListener("pause", () => {
    if (audio.currentTime < sample.clipEnd) button.textContent = "Play";
  });

  return section;
};

